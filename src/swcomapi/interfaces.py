def __getattr__(name):
    """Build an empty Protocol for an interface name (PEP 562)."""
    if name not in _NAMES:
        raise AttributeError(
            f"module {__name__!r} has no interface {name!r}. "
            f"Try swcomapi.apidoc.find({name!r}) to search."
        )
    built = type(name, (Protocol,), {"__module__": __name__})
    globals()[name] = built
    return built


